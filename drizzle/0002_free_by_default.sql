/*
  المتجر الجديد بيفتح مجاني — والتجربة بتتطلب.

  التجربة كانت بتتدّي تلقائي في التسجيل، فكل حساب اتعمل قبل التعديل
  ده خرج وكل المميزات مفتوحة عنده ٣ أيام من غير ما يطلبها — يعني
  القفل كان موجود في الكود ومش شغّال على حد فعلًا.

  الملف ده بيرجّع المتاجر دي للباقة المجانية عشان تبدأ من نفس نقطة
  أي متجر جديد، وتقدر تبدأ تجربتها بإيدها وقت ما تجهز.

  **بيمسّ التجارب اللي اتوهبت تلقائي بس**: الشرط `activated_at IS NULL`
  بيستثني أي متجر فعّلته الإدارة أو بدأ تجربته بنفسه بعد التعديل،
  و`subscribed_until` بيستثني أي مشترك دافع.

  idempotent: تنفيذه تاني ما بيغيّرش حاجة، لأن الصفوف بتبقى بقت
  `free` والشرط مش هيلاقيها.
*/

UPDATE "stores"
SET "status" = 'free',
    "plan" = NULL,
    "trial_ends_at" = NULL
WHERE "status" = 'trial'
  AND "activated_at" IS NULL
  AND ("subscribed_until" IS NULL OR "subscribed_until" < now());
