-- شكل الصورة في النشر التلقائي
--
-- التوجيه كان ثابتًا: «مكان حقيقي، وممنوع خلفية سادة» لكل منتج.
-- فالتاجر اللي كتب «خلفية سادة» كان بيطلب الممنوع، والممنوع كان
-- بيغلب. دلوقتي كل جدول ليه شكل: يختار لوحده · مكان حقيقي · خلفية
-- سادة · مينيمال · ثري دي · من فوق · فخم غامق.

alter table content_schedules
  -- `auto` افتراضي: الجداول القديمة بتفضل ماشية بكلام التاجر المكتوب
  -- في `style` — «خلفية سادة» جوّاه بتتفهم وبتغلب
  add column if not exists image_style text not null default 'auto';
