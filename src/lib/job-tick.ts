import 'server-only'
import { after } from 'next/server'

/**
 * سحب خفيف للطابور مع حركة الموقع.
 *
 * ## المشكلة
 * المهام المؤجّلة (زي طلب تأكيد الطلب بعد ٥ دقايق) بتستنى عاملًا
 * يسحبها. والعامل بيتنادى من مهمة Vercel المجدولة — **مرة واحدة في
 * اليوم** على الخطة المجانية. يعني رسالة المفروض تطلع بعد ٥ دقايق
 * ممكن تستنى ٢٤ ساعة، وتوصل العميل بعد ما نسي الطلب أصلًا.
 *
 * ## الحل
 * كل زيارة لواجهة متجر بتسحب مهمتين من الطابور لو حان وقتهم. المتجر
 * اللي بيستقبل طلبات بيبقى عليه حركة بالضرورة — فاللي محتاج المهام
 * دي عنده الحركة اللي بتشغّلها.
 *
 * ## والمهلة عشان ما يبقاش حِمل
 * دقيقة بين كل سحب وسحب **لكل نسخة**. من غيرها، متجر عليه ضغط كان
 * هيعمل استعلام طابور مع كل زيارة صفحة. والرقم مش دقيق بين النسخ —
 * وده مقبول: القفل في `claim` بيمنع إن اتنين ياخدوا نفس المهمة، فأسوأ
 * حالة استعلام زيادة لا تنفيذ مزدوج.
 *
 * ## بيجري بعد الرد
 * جوّه `after`، فالزائر ما بيستناش الطابور. وأي فشل بيتسجّل ولا بيلمس
 * الصفحة اللي هو فاتحها.
 */

let lastTick = 0
const EVERY_MS = 60_000

export function jobTick(): void {
  const now = Date.now()
  if (now - lastTick < EVERY_MS) return
  lastTick = now

  after(
    (async () => {
      const { drainJobs } = await import('./jobs')
      await drainJobs(3)
    })().catch((e) => console.error('فشل سحب الطابور:', e)),
  )
}
