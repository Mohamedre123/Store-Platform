import 'server-only'
import { after } from 'next/server'

/**
 * سحب خفيف للطابور مع حركة الموقع.
 *
 * ## المشكلة
 * المهام المؤجّلة (زي طلب تأكيد الطلب بعد ٥ دقايق) بتستنى عاملًا
 * يسحبها. والعامل بيتنادى من مهمة Vercel المجدولة — **مرة واحدة في
 * اليوم** على الخطة المجانية. يعني رسالة المفروض تطلع بعد ٥ دقايق
 * ممكن تستنى ٢٤ ساعة، وتوصل العميل بعد ما نسي الطلب أصلًا.
 *
 * ## الحل
 * كل زيارة لواجهة متجر بتسحب مهمتين من الطابور لو حان وقتهم. المتجر
 * اللي بيستقبل طلبات بيبقى عليه حركة بالضرورة — فاللي محتاج المهام
 * دي عنده الحركة اللي بتشغّلها.
 *
 * ## والمهلة عشان ما يبقاش حِمل
 * دقيقة بين كل سحب وسحب **لكل نسخة**. من غيرها، متجر عليه ضغط كان
 * هيعمل استعلام طابور مع كل زيارة صفحة. والرقم مش دقيق بين النسخ —
 * وده مقبول: القفل في `claim` بيمنع إن اتنين ياخدوا نفس المهمة، فأسوأ
 * حالة استعلام زيادة لا تنفيذ مزدوج.
 *
 * ## بيجري بعد الرد
 * جوّه `after`، فالزائر ما بيستناش الطابور. وأي فشل بيتسجّل ولا بيلمس
 * الصفحة اللي هو فاتحها.
 */

/**
 * ## ليه المهلة قصرت
 * كانت دقيقة كاملة **لكل نسخة**. والنسخة الدافية بتخدم كذا طلب ورا
 * بعض، فأول واحد بيسحب والباقي بيتخطّى — ولو التاجر بيتنقّل بين صفحتين
 * في نص دقيقة، ولا سحبة بتحصل بعد الأولى.
 *
 * وطلب التأكيد مهلته دقيقة واحدة عند بعض التجّار، فمهلة سحب دقيقة
 * معناها إن الرسالة ممكن تستنّى دورة كاملة زيادة. عشرين ثانية بتخلّي
 * السحب يلحق أقصر مهلة ممكنة، والقفل في `claim` بيمنع التنفيذ المزدوج
 * فأسوأ حالة استعلام زيادة.
 */
let lastTick = 0
const EVERY_MS = 20_000

/**
 * سحب **منتظَر** لا مؤجّل.
 *
 * ## ليه ده موجود جنب `jobTick`
 * `after()` بتشتغل محليًا وما اشتغلتش على الاستضافة: جرّبنا على
 * الإنتاج أربع زيارات متباعدة، والصفحة اتولّدت طازة في كل مرة
 * (`X-Vercel-Cache: MISS`) — يعني التخطيط اشتغل و`jobTick` اتنادت —
 * والطابور فضل `pending` بـ`attempts: 0` ما اتلمسش.
 *
 * الشغل اللي بيتأجّل لبعد الرد بيموت مع الدالة. والمهمة اللي بتستنّى
 * دقيقة مالهاش قيمة لو العامل اللي هيسحبها بيتقتل قبل ما يبدأ.
 *
 * فبننادي دي من مسار حقيقي (`/api/track` اللي المتصفح بيندهه مع كل
 * زيارة) وبننتظرها. الزائر مش بيستنّى الرد أصلًا — `sendBeacon` بتبعت
 * وتمشي — فالانتظار هنا مالوش تكلفة عليه.
 */
export async function drainDueJobs(): Promise<void> {
  const now = Date.now()
  if (now - lastTick < EVERY_MS) return
  lastTick = now

  try {
    const { drainJobs } = await import('./jobs')
    const summary = await drainJobs(5)
    if (summary.picked > 0) {
      console.log(`طابور: سحب ${summary.picked} · نجح ${summary.done} · فشل ${summary.failed}`)
    }
  } catch (e) {
    console.error('فشل سحب الطابور:', e)
  }
}

export function jobTick(): void {
  const now = Date.now()
  if (now - lastTick < EVERY_MS) return
  lastTick = now

  after(
    (async () => {
      const { drainJobs } = await import('./jobs')
      const summary = await drainJobs(5)
      /*
        بنسجّل لما نسحب فعلًا.

        قعدنا ندوّر على سبب إن طلب التأكيد مش بيتبعت، والطابور كان فيه
        ١١ مهمة `pending` بـ`attempts: 0` — يعني محدّش لمسها أصلًا.
        ومكانش فيه أي سطر في السجل يقول إن السحب اشتغل ولا لأ، فالسؤال
        «العامل بيجري؟» مكانش ليه إجابة غير التخمين.
      */
      if (summary.picked > 0) {
        console.log(
          `طابور: سحب ${summary.picked} · نجح ${summary.done} · فشل ${summary.failed}`,
        )
      }
    })().catch((e) => console.error('فشل سحب الطابور:', e)),
  )
}
