/**
 * قناة إشعار العميل — اختيار التاجر لحظة الإجراء.
 *
 * ## المشكلة
 * كل تغيير حالة كان بيبعت على البريد **والواتساب** مع بعض، من غير
 * ما التاجر يتحكم. وده غلط في حالات كتير يومية:
 *
 * - العميل رد على الواتساب خلاص واتفقوا؛ رسالة تانية إزعاج.
 * - التاجر بيصلّح حالة اتحطّت غلط؛ ما يصحّش العميل ياخد إشعارين
 *   متناقضين.
 * - باقة الواتساب محدودة (بعض المزوّدين رسالة كل دقيقة على المجاني)،
 *   فالتاجر عايز يحجزها للحاجات المهمة.
 *
 * ## الاختيار قبل الإجراء لا بعده
 * التاجر بيختار القناة مرة، وبعدها أي زرار حالة يدوسه (تأكيد، تسليم،
 * إلغاء…) بيمشي عليها. لو خلّينا الاختيار في نافذة بتفتح مع كل ضغطة،
 * التاجر اللي بيغيّر عشرين طلب بيقفلها من غير ما يقراها.
 *
 * ## `none` مش «إلغاء»
 * الحالة بتتغيّر في كل الأحوال؛ `none` معناها «غيّرها في الهدوء».
 * التاجر اللي بيرتّب طلبات قديمة مش عايز يصحّي عملاءه بإشعارات على
 * حاجة عدّت.
 */

export type NotifyChannel = 'email' | 'whatsapp' | 'both' | 'none'

export const NOTIFY_CHANNELS: Array<{ key: NotifyChannel; label: string; hint: string }> = [
  { key: 'both', label: 'بريد + واتساب', hint: 'يوصل على الاتنين' },
  { key: 'whatsapp', label: 'واتساب بس', hint: 'أسرع طريق للعميل المصري' },
  { key: 'email', label: 'بريد بس', hint: 'للعميل اللي بيتابع بريده' },
  { key: 'none', label: 'من غير إشعار', hint: 'غيّر الحالة في الهدوء' },
]

/** القيمة الآمنة لو الجاي من المتصفح مش معروف */
export function normalizeChannel(value: unknown): NotifyChannel {
  return value === 'email' || value === 'whatsapp' || value === 'none' || value === 'both'
    ? value
    : 'both'
}

export const wantsEmail = (c: NotifyChannel) => c === 'email' || c === 'both'
export const wantsWhatsapp = (c: NotifyChannel) => c === 'whatsapp' || c === 'both'

