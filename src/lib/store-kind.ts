/**
 * بيستنتج النشاط من أسماء الأقسام والمنتجات.
 *
 * الأقسام بتتحسب بتلاتة أضعاف المنتج الواحد: التاجر بيسمّي القسم
 * «عطور» عن قصد، والمنتج ممكن اسمه اسم موديل مالوش دلالة.
 */
export function inferStoreKind(input: {
  categories?: string[]
  products?: string[]
  /** وصف التاجر لمتجره لو كتبه — أقوى إشارة موجودة */
  brief?: string | null
}): StoreKind {
  const scores = new Map<StoreKind, number>()

  const scan = (text: string, weight: number) => {
    const hay = text.toLowerCase()
    for (const [kind, words] of Object.entries(SIGNALS) as Array<[StoreKind, string[]]>) {
      for (const w of words) {
        if (hay.includes(w.toLowerCase())) {
          scores.set(kind, (scores.get(kind) ?? 0) + weight)
          /* كلمة واحدة من النشاط كفاية لهذا النص — التكرار مش دليل أقوى */
          break
        }
      }
    }
  }

  if (input.brief) scan(input.brief, 4)
  for (const c of input.categories ?? []) scan(c, 3)
  for (const p of input.products ?? []) scan(p, 1)

  let best: StoreKind = 'generic'
  let top = 0
  for (const [kind, score] of scores) {
    if (score > top) {
      top = score
      best = kind
    }
  }

  /* إشارة ضعيفة أوي = تخمين. والعام أأمن من تخصيص غلط. */
  return top >= 3 ? best : 'generic'
}

