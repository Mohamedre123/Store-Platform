/**
 * وسوم الرأس اللي التاجر بيحطّها — والفحص اللي بيخلّيها آمنة.
 *
 * ## المشكلة اللي الملف ده بيحلّها
 * جوجل سيرش كونسول وميتا وبنترست وتيك توك كلهم بيطلبوا وسم `meta`
 * في رأس الصفحة عشان يتأكدوا إن الموقع بتاعك. من غير خانة بيحطّه
 * فيها، التاجر **مش قادر يوثّق موقعه في جوجل** — يعني مش شايف
 * كلمات البحث اللي بتجيبه ولا قادر يرفع خريطة موقعه. ده نقص حقيقي
 * مش رفاهية.
 *
 * ## وليه مش خانة HTML مفتوحة زي المنافس
 * متاجر التجّار كلها بتتقدّم من نطاقات فرعية من **نطاقنا**. سكربت
 * بيتحقن في رأس متجر بيجري على `متجره.نطاقنا` — يعني أي حد يسجّل
 * حسابًا مجانيًّا يقدر يستضيف جافاسكربت خبيثة على نطاق فيه سمعة كل
 * تاجر تاني على المنصة. والضرر (تحذير جوجل، حجب في المتصفحات، بلاغ
 * تصيّد) بيقع على الكل مش على صاحب الحساب.
 *
 * والسكربتات ليها مسارها المضبوط أصلًا: صفحة الإضافات بتركّب
 * بكسلات فيسبوك وتيك توك وسناب وجوجل بمعرّفات مفحوصة. فاللي فاضل
 * للخانة دي هو التوثيق، والتوثيق `meta` وبس.
 *
 * ## الفحص بالسماح لا بالمنع
 * قايمة ممنوعات (`<script>` و`onerror=` و`javascript:`) بتتلفّ
 * بعشر طرق — الترميز، والتعليقات، والوسوم الناقصة. القايمة هنا
 * **مسموحات**: أي حاجة مش وسم `meta` بخصائص معروفة بتترفض. اللي
 * بيتلفّ حواليها لازم يعدّي على وسم مسموح، ووسم `meta` مالوش أي
 * سلوك ينفّذ.
 */

/**
 * الخصائص اللي وسم التوثيق بيستعملها فعلًا.
 *
 * **`http-equiv` مش فيها عن قصد.** `<meta http-equiv="refresh"
 * content="0;url=//مكان-تاني">` بيحوّل كل زائر للمتجر لأي موقع —
 * يعني تاجر يقدر يستعمل نطاقنا كصفحة تحويل لتصيّد، والزائر شايف
 * نطاقنا في شريط العنوان لحظة التحويل. ده وسم `meta` سليم شكلًا،
 * فقايمة الوسوم المسموحة وحدها ما كانتش هتمسكه — الاختبار هو اللي
 * مسكه.
 *
 * و`charset` مش فيها كمان: الصفحة بتحدّد ترميزها، ووسم تاني
 * بيتناقض معاه بيبوّظ العربي في الصفحة كلها.
 */
const ALLOWED_ATTRS = new Set(['name', 'content', 'property'])

/**
 * الحد الأقصى — عشر وسوم.
 *
 * التاجر اللي بيوثّق في جوجل وبينج وميتا وبنترست وتيك توك عايز
 * خمسة. العشرة مساحة مريحة، وفي نفس الوقت بتمنع حد يحشر كيلوبايتات
 * في رأس كل صفحة بيحمّلها كل زائر.
 */
const MAX_TAGS = 10

export type HeadHtmlResult =
  | { ok: true; value: string }
  | { ok: false; error: string }

/**
 * بيفحص اللي التاجر كتبه وبيرجّع نسخة نظيفة أو سبب الرفض.
 *
 * بيرجّع الوسوم بعد إعادة بنائها من الاسم والقيمة لا زي ما اتكتبت:
 * كده أي حاجة برّه الخصائص المسموحة بتتشال بالبناء نفسه، من غير ما
 * نعتمد على إننا فكّرنا في كل شكل ممكن تتكتب بيه.
 */
export function sanitizeHeadHtml(input: string): HeadHtmlResult {
  const raw = input.trim()
  if (!raw) return { ok: true, value: '' }
  if (raw.length > 4000) return { ok: false, error: 'الوسوم أطول من اللازم — ٤٠٠٠ حرف كحد أقصى' }

  /*
    أي حاجة مش وسم بتترفض بالاسم.

    الرسالة بتقول **إيه** اللي اترفض عشان التاجر يعرف يصلّحه: «مش
    مسموح» لوحدها بتخلّيه يقعد يجرّب ويفشل.
  */
  const tags = raw.match(/<[^>]*>/g) ?? []
  const outsideTags = raw.replace(/<[^>]*>/g, '').trim()
  if (outsideTags) {
    return { ok: false, error: 'الخانة دي لوسوم `meta` بس — شيل أي كلام برّه الوسوم' }
  }
  if (tags.length === 0) {
    return { ok: false, error: 'ما لقيتش أي وسم. الصق الوسم زي ما جوجل أو ميتا إدّاهولك.' }
  }
  if (tags.length > MAX_TAGS) {
    return { ok: false, error: `${MAX_TAGS} وسوم كحد أقصى` }
  }

  const out: string[] = []

  for (const tag of tags) {
    const nameMatch = tag.match(/^<\s*([a-zA-Z][a-zA-Z0-9-]*)/)
    const tagName = nameMatch?.[1]?.toLowerCase()

    if (tagName !== 'meta') {
      return {
        ok: false,
        error: tagName
          ? `وسم \`${tagName}\` مش مسموح. الخانة دي لوسوم \`meta\` بتاعت التوثيق بس — البكسلات من صفحة الإضافات.`
          : 'فيه وسم مش مفهوم — الصق الوسم زي ما جالك بالظبط',
      }
    }

    /* الخصائص بتتقرا واحدة واحدة، والوسم بيتعاد بناؤه منها */
    const attrs: Array<[string, string]> = []
    const attrRe = /([a-zA-Z][a-zA-Z0-9-]*)\s*=\s*"([^"]*)"|([a-zA-Z][a-zA-Z0-9-]*)\s*=\s*'([^']*)'/g
    let m: RegExpExecArray | null

    while ((m = attrRe.exec(tag))) {
      const key = (m[1] ?? m[3]).toLowerCase()
      const value = m[2] ?? m[4] ?? ''

      if (!ALLOWED_ATTRS.has(key)) {
        return { ok: false, error: `خاصية \`${key}\` مش مسموحة في وسم التوثيق` }
      }
      /*
        القيمة ما تحتويش علامات — `"` بيقفل الخاصية و`<` بيفتح وسمًا.
        الاتنين هما الطريق الوحيد للخروج من الوسم بعد إعادة البناء.
      */
      if (/["'<>]/.test(value)) {
        return { ok: false, error: 'فيه علامات غريبة في قيمة الوسم — الصقه زي ما جالك' }
      }
      attrs.push([key, value])
    }

    if (attrs.length === 0) {
      return { ok: false, error: 'فيه وسم `meta` فاضي — شيله' }
    }

    out.push(`<meta ${attrs.map(([k, v]) => `${k}="${v}"`).join(' ')} />`)
  }

  return { ok: true, value: out.join('\n') }
}
