import { pgTable, uuid, text, boolean, integer, jsonb, timestamp, index, uniqueIndex } from 'drizzle-orm/pg-core'
import { stores } from './tenancy'
import { createdAt, updatedAt, money } from './_shared'

export type CouponType = 'percent' | 'fixed' | 'free_shipping'
export type CouponAppliesTo = 'all' | 'products' | 'categories'
export type CouponEligibility = 'all' | 'first_order' | 'tier' | 'specific_customers'

export const coupons = pgTable(
  'coupons',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    storeId: uuid('store_id').notNull().references(() => stores.id, { onDelete: 'cascade' }),
    code: text('code').notNull(),
    description: text('description'),

    type: text('type').$type<CouponType>().notNull().default('percent'),
    /** نسبة مئوية بنقاط الأساس (1000 = 10%) أو مبلغ ثابت بالوحدة الصغرى */
    value: integer('value').notNull().default(0),
    maxDiscount: money('max_discount'), // سقف الخصم لكوبونات النسبة
    minOrder: money('min_order'),

    appliesTo: text('applies_to').$type<CouponAppliesTo>().notNull().default('all'),
    targetIds: jsonb('target_ids').$type<string[]>().notNull().default([]),

    eligibility: text('eligibility').$type<CouponEligibility>().notNull().default('all'),
    eligibilityValue: jsonb('eligibility_value').$type<string[]>().notNull().default([]),

    usageLimit: integer('usage_limit'),
    usageLimitPerCustomer: integer('usage_limit_per_customer').notNull().default(1),
    usedCount: integer('used_count').notNull().default(0),

    /** كوبون هدية يُولَّد تلقائيًا (استرداد سلة، صفحة شكر، مكافأة ولاء) */
    isAutoGenerated: boolean('is_auto_generated').notNull().default(false),

    startsAt: timestamp('starts_at', { withTimezone: true }),
    endsAt: timestamp('ends_at', { withTimezone: true }),
    isActive: boolean('is_active').notNull().default(true),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex('coupons_store_code_unique').on(t.storeId, t.code),
    index('coupons_store_active_idx').on(t.storeId, t.isActive),
  ],
)

export const couponUses = pgTable(
  'coupon_uses',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    couponId: uuid('coupon_id').notNull().references(() => coupons.id, { onDelete: 'cascade' }),
    storeId: uuid('store_id').notNull().references(() => stores.id, { onDelete: 'cascade' }),
    orderId: uuid('order_id').notNull(),
    customerId: uuid('customer_id'),
    amount: money('amount'),
    createdAt: createdAt(),
  },
  (t) => [
    index('coupon_uses_coupon_idx').on(t.couponId),
    index('coupon_uses_customer_idx').on(t.customerId),
  ],
)

export type OfferType = 'quantity_break' | 'fixed_bundle' | 'mix_bundle' | 'buy_x_get_y'

/** عروض الكمية والباقات */
export const offers = pgTable(
  'offers',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    storeId: uuid('store_id').notNull().references(() => stores.id, { onDelete: 'cascade' }),
    type: text('type').$type<OfferType>().notNull(),
    name: text('name').notNull(),
    description: text('description'),
    /**
     * quantity_break: { tiers: [{ qty, discountBps }] }
     * fixed_bundle:   { productIds: [], bundlePrice }
     * mix_bundle:     { categoryIds: [], pickCount, bundlePrice }
     * buy_x_get_y:    { buyProductIds, buyQty, getProductIds, getQty, discountBps }
     */
    config: jsonb('config').$type<Record<string, unknown>>().notNull().default({}),
    productIds: jsonb('product_ids').$type<string[]>().notNull().default([]),
    badge: text('badge'),
    startsAt: timestamp('starts_at', { withTimezone: true }),
    endsAt: timestamp('ends_at', { withTimezone: true }),
    isActive: boolean('is_active').notNull().default(true),
    sortOrder: integer('sort_order').notNull().default(0),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('offers_store_active_idx').on(t.storeId, t.isActive)],
)

/** المسوّقون بالعمولة */
export const affiliates = pgTable(
  'affiliates',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    storeId: uuid('store_id').notNull().references(() => stores.id, { onDelete: 'cascade' }),
    name: text('name').notNull(),
    phone: text('phone'),
    email: text('email'),
    code: text('code').notNull(),
    commissionType: text('commission_type').$type<'percent' | 'fixed'>().notNull().default('percent'),
    commissionValue: integer('commission_value').notNull().default(1000), // 10%
    balance: money('balance'),
    totalEarned: money('total_earned'),
    totalPaid: money('total_paid'),
    clicks: integer('clicks').notNull().default(0),
    conversions: integer('conversions').notNull().default(0),
    isActive: boolean('is_active').notNull().default(true),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex('affiliates_store_code_unique').on(t.storeId, t.code),
    index('affiliates_store_idx').on(t.storeId),
  ],
)

